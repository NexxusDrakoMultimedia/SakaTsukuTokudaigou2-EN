"""Loader of the open-font glyph set used by `build_patch.py --open-font on` (docs/open-font.md).

The data lives in translation/fonts/ (generated by tools/re/font/render_open_font.py, the TTF itself is not in the repository):
    robotocondensed_medium_12x24.bin          94 glyphs x 144 bytes (12x24, 4 bpp, 0 = ink, 15 = paper), slots 0x21..0x7E in order
    robotocondensed_medium_12x24.widths.json  provenance + "advance": {"0x20": 12, ...} the advance table of the glyph set
Glyph art: Roboto Condensed Medium, Copyright 2011 The Roboto Project Authors, SIL Open Font License 1.1 (LICENSES/OFL-1.1.txt).
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA_DIR = os.path.join(ROOT, 'translation', 'fonts')
NAME = 'robotocondensed_medium_12x24'
FIRST, LAST = 0x21, 0x7E
GLYPH_BYTES = 144


class OpenFontError(Exception):
    pass


def load(data_dir=None, name=NAME):
    """-> (glyphs {byte: 144 bytes} for 0x21..0x7E, advance table bytes(256)).  Checks size, checksum and table plausibility."""
    d = data_dir or DATA_DIR
    try:
        raw = open(os.path.join(d, name + '.bin'), 'rb').read()
        with open(os.path.join(d, name + '.widths.json'), encoding='utf-8') as fh:
            meta = json.load(fh)
    except OSError as e:
        raise OpenFontError('open font data missing: %s' % e)
    n = LAST - FIRST + 1
    if len(raw) != n * GLYPH_BYTES:
        raise OpenFontError('%s.bin is %d bytes, expected %d' % (name, len(raw), n * GLYPH_BYTES))
    if hashlib.sha256(raw).hexdigest() != meta.get('glyph_sha256'):
        raise OpenFontError('%s.bin does not match glyph_sha256 of the .widths.json (regenerate both together)' % name)
    glyphs = {FIRST + i: raw[i * GLYPH_BYTES:(i + 1) * GLYPH_BYTES] for i in range(n)}
    table = bytearray(256)
    for k, v in meta['advance'].items():
        b = int(k, 16)
        if not (0 <= b < 256 and 1 <= v <= 24):
            raise OpenFontError('bad advance entry %s: %r' % (k, v))
        table[b] = v
    if not table[0x20] or table[0] != table[0x20]:
        raise OpenFontError('the table needs the space at index 0x20 and 0 (equal)')
    return glyphs, bytes(table)


def apply_glyphs(font, glyphs):
    """set the 94 slots in a font.Font object (in place)"""
    import font as F
    for b, g in glyphs.items():
        font.set_half(F.half_index(b), g)
    return font


def table(data_dir=None):
    return load(data_dir)[1]
