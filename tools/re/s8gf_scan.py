"""s8gf: classify the use of every pointer to a half-width (hwptr) string of every overlay (driver of tools/hwguard.py).

Writes, from the ORIGINAL overlay bytes and the translation DB:
  --tsv  build/s8gf_classify.tsv     one row per pointer-referenced hwptr record: id, overlay, old addr, sites, use, class, en, slot, why
                                     (rows of class text with only `ptrtab` sites are the plain string-pointer tables: 99.9 percent)
  --deny translation/hw_inplace.tsv  the data-driven denylist: every record that is not class text (base / unknown / head), plus the
                                     lines of the existing file that are marked `manual` (kept)
usage:  python -I -X utf8 tools/re/s8gf_scan.py [--tsv FILE] [--deny FILE] [--check] [SOURCE_SUBSTR ...]
--check  compares the result with the existing denylist file instead of writing it (exit 1 on a difference)
Read-only on everything except the two output files.  Method and rules: tools/hwguard.py, docs/hw-relocation.md section 6.
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import hwguard as G  # noqa: E402
import textdb  # noqa: E402


def classify_all(subs=()):
    """-> list of row dicts for every pointer-referenced hwptr record (not hwpool) of the DB"""
    out = []
    for jp in sorted(glob.glob(os.path.join(ROOT, 'translation', '*.jsonl'))):
        bn = os.path.basename(jp)
        if bn.startswith('BCAST'):
            continue
        source = bn[:-6].replace('__', '/')
        if subs and not any(s in source.upper() for s in subs):
            continue
        recs = [json.loads(l) for l in open(jp, encoding='utf-8') if l.strip()]
        hw = [r for r in recs if r.get('fmt') == 'hwptr']
        if not any(r.get('refs') for r in hw):
            continue
        img = textdb.load_image(source)
        ix = G.ImageIndex(img.data, img.base)
        heads = G.array_heads(hw, [r for r in recs if r.get('fmt') != 'hwptr'])
        for r in hw:
            if not r.get('refs') or 'hwpool' in (r.get('ctx') or ''):
                continue
            off = int(r['id'].rsplit('#', 1)[1], 16)
            sites = ix.site_report(off)
            cls, why = G.site_verdict(sites)
            if off in heads:
                cls, why = 'head', 'head of a record array (recarray / hwpool neighbours at +S, +2S)'
            out.append(dict(id=r['id'], source=source, off=off, en=r.get('en') or '', ja=r.get('ja'), slot=r.get('slot') or r['max_bytes'],
                            sites=sites, kinds=','.join(sorted({s[0] for s in sites})), cls=cls, why=why))
    return out


def main(argv):
    tsv = deny = None
    subs = []
    check = False
    i = 1
    while i < len(argv):
        if argv[i] == '--tsv':
            tsv = argv[i + 1]
            i += 2
        elif argv[i] == '--deny':
            deny = argv[i + 1]
            i += 2
        elif argv[i] == '--check':
            check = True
            i += 1
        else:
            subs.append(argv[i].upper())
            i += 1
    out = classify_all(subs)
    counts = {}
    for r in out:
        counts[(r['cls'], r['kinds'])] = counts.get((r['cls'], r['kinds']), 0) + 1
    for k, v in sorted(counts.items()):
        print(k, v)
    print('records', len(out))
    if tsv:
        with open(tsv, 'w', encoding='utf-8', newline='\n') as f:
            f.write('id\toverlay\told_addr\tsites\tuse\tclass\ten\tslot\twhy\n')
            for r in out:
                f.write('%s\t%s\t%#x\t%s\t%s\t%s\t%s\t%d\t%s\n' % (
                    r['id'], r['source'], r['off'], ' '.join('%s@%x' % (x[0], x[1]) for x in r['sites']),
                    ';'.join('%s:%s' % (x[0], x[2]) for x in r['sites'] if x[0] != 'ptrtab') or 'ptrtab', r['cls'], r['en'], r['slot'], r['why']))
    if deny:
        old = {}
        if os.path.exists(deny):
            old = {k: v for k, v in G.load_deny(deny).items() if v[0] == 'manual'}
        lines = ['# id\tclass\treason',
                 '# Records that --hw-relocate must never move (and whose slot is never lent to other strings): the pointer is the BASE of a table',
                 '# (base / head) or its use could not be shown to be a text pointer (unknown).  Generated by tools/re/s8gf_scan.py (rules in',
                 '# tools/hwguard.py, docs/hw-relocation.md section 6); lines of class `manual` are hand-written and survive a regeneration.']
        new = {r['id']: (r['cls'], r['why']) for r in out if r['cls'] != 'text'}
        new.update(old)
        for k in sorted(new, key=lambda x: (x.rsplit('#', 1)[0], int(x.rsplit('#', 1)[1], 16))):
            lines.append('%s\t%s\t%s' % (k, new[k][0], new[k][1]))
        text = '\n'.join(lines) + '\n'
        if check:
            cur = open(deny, encoding='utf-8').read() if os.path.exists(deny) else ''
            print('denylist up to date' if cur == text else 'denylist DIFFERS from the scan (rerun without --check)')
            return 0 if cur == text else 1
        with open(deny, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', deny, len(new), 'records')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
