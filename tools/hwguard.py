"""hwguard: which half-width pointer strings (fmt hwptr) may be MOVED by `--hw-relocate` (docs/hw-relocation.md section 6).

Why.  Relocating a string rewrites every pointer word that names it.  That is only right when the pointer is a TEXT pointer.  When
the pointer is the BASE of a table (the string is the first element of an array that code indexes with idx * stride, e.g. SCDRF.BIN
0x37df0 'Damui' = record 0 of the 56 byte player table, 11 literal sites; the byte table 'Nuchitos' in about 38 overlays) the move
breaks the game: the code reads table[idx * stride + base] and gets the string pool.  The extraction cannot tell the two apart
(`stride-table(in-place only)` sits in the ctx of ALL hwptr records), so this module decides from the ORIGINAL overlay bytes and
from a small data file.

Two layers, both fail safe (a record that cannot be shown to be text stays where it is):

  1. DATA   translation/hw_inplace.tsv  (id TAB class TAB reason): records that must never move or lend their slot.  Generated by
            tools/re/s8gf_scan.py from layer 2 plus manual entries; `is_denied(id)` / `load_deny()`; textfmt_hwkana.is_relocatable
            and tools/refit.py honour it (a refit form that needs relocation of a denied record is skipped).
  2. CODE   site_verdict(): every pointer word ("site") of the record is classified from the image bytes:
              ptrtab  the word is not loaded by code and has an in-image pointer next to it (+-4): a table of string pointers
              lit     the word is the literal of a `mov.l @(d,pc),Rn`; the use of Rn is followed (use tags below)
              field   a lone pointer field of a data record (nothing known about its use)
            use tags: add / mul / mulb / idx / disp / disp0 / shift = index arithmetic or record field access (BASE);
                      call = the register is only passed to jsr / bsr in r4..r7; stored / read = kept in memory / read bytewise.
            The record is TEXT only when every site is `ptrtab` or a `lit` whose only tag is `call`; BASE when a site has a base tag;
            UNKNOWN otherwise (field, stored, read, no use).  Only TEXT may move.
  Also BASE: the head of a record array (Rule A / B of array_heads()).

The analysis is a heuristic over straight-line SH-4 code (36 instructions behind the load, 6 in front for a hoisted multiply).  It is
meant to be conservative: every doubt lands in UNKNOWN.  A literal is only believed inside a +-256 byte window that holds at least 2
function markers (rts / sts.l pr,@-r15 / lds.l @r15+,pr), because 0xDnXX halfwords are also kana bytes and pointer words.
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DENY_FILE = os.path.join(ROOT, 'translation', 'hw_inplace.tsv')

BASE_TAGS = {'add', 'mul', 'idx', 'disp', 'disp0', 'shift'}


# ------------------------------------------------------------------ data layer
_DENY = {'path': None, 'mtime': None, 'map': {}}


def load_deny(path=None):
    """{id: (class, reason)} of the denylist file (cached per path + mtime); a missing file is an empty list"""
    p = path or DENY_FILE
    try:
        mt = os.path.getmtime(p)
    except OSError:
        return {}
    if _DENY['path'] == p and _DENY['mtime'] == mt:
        return _DENY['map']
    out = {}
    with open(p, encoding='utf-8') as f:
        for ln, line in enumerate(f, 1):
            line = line.rstrip('\r\n')
            if not line.strip() or line.startswith('#'):
                continue
            c = line.split('\t')
            if len(c) < 2 or not re.match(r'^[^#\t]+#[0-9a-f]+$', c[0]) or c[1] not in ('base', 'unknown', 'head', 'manual'):
                raise ValueError('%s:%d: expected "SOURCE#hexoff<TAB>base|unknown|head|manual<TAB>reason"' % (p, ln))
            out[c[0]] = (c[1], c[2] if len(c) > 2 else '')
    _DENY.update(path=p, mtime=mt, map=out)
    return out


def is_denied(rec_id, path=None):
    return rec_id in load_deny(path)


def require_deny(path=None):
    """fail-safe for guarded relocation (apply_relocate guard=True): the denylist file must exist and hold entries.  A missing file reads as an
    EMPTY list in load_deny (library use), which would silently lift every `head` / `unknown` / `manual` denial and leave only the build-time
    code check; a build must stop instead (s8gkc)."""
    p = path or DENY_FILE
    m = load_deny(p)
    if not m:
        raise RuntimeError('%s is missing or empty: refusing guarded hw relocation (regenerate it with tools/re/s8gf_scan.py --deny)' % p)
    return m


# ------------------------------------------------------------------ code layer
def literal_loads(d):
    """{literal file offset: [(pc, reg, in_code)]} for every `mov.l @(d,pc),Rn` (0xDnXX) of the image; in_code = the pc lies in a
    +-256 byte window with at least 2 function markers (see the module doc).  The ones outside code are kept for the base check."""
    from array import array
    out = {}
    n = len(d) // 2
    hw = array('H')
    hw.frombytes(bytes(d[:n * 2]))
    if sys.byteorder != 'little':
        hw.byteswap()
    cum = array('i', bytes(4 * (n + 1)))
    c = 0
    for i, w in enumerate(hw):
        if w == 0x000B or w == 0x4F22 or w == 0x4F26:
            c += 1
        cum[i + 1] = c
    for i, w in enumerate(hw):
        if w >> 12 == 0xD:
            pc = i * 2
            lit = ((pc + 4) & ~3) + (w & 0xFF) * 4
            if lit + 4 <= len(d):
                out.setdefault(lit, []).append((pc, (w >> 8) & 15, cum[min(n, i + 128)] - cum[max(0, i - 128)] >= 2))
    return out


def decode(w):
    """(kind, n, m, x) of the SH-4 instruction word for the patterns the use analysis needs; kind 'other' otherwise"""
    t, n, m, l = w >> 12, (w >> 8) & 15, (w >> 4) & 15, w & 15
    if t == 0xD:
        return ('ldlit', n, 0, w & 0xFF)
    if t == 6 and l == 3:
        return ('mov', n, m, 0)
    if t == 6 and l in (0, 1, 2, 4, 5, 6):
        return ('rd', n, m, l)                       # mov.b/w/l @Rm(+),Rn : reads memory at Rm
    if t == 2 and l in (0, 1, 2, 4, 5, 6):
        return ('wr', n, m, l)                       # mov.b/w/l Rm,@Rn / @-Rn : writes Rm to memory at Rn
    if t == 1:
        return ('wrd', n, m, l)                      # mov.l Rm,@(d,Rn)
    if t == 5:
        return ('rdd', n, m, l)                      # mov.l @(d,Rm),Rn
    if t == 8 and n in (4, 5):
        return ('rdd0', 0, m, w & 15)                # mov.b/w @(d,Rm),r0
    if t == 8 and n in (0, 1):
        return ('wrd0', m, 0, w & 15)                # mov.b/w r0,@(d,Rn)  (Rn is in the m field here)
    if t == 0 and l in (0xC, 0xD, 0xE):
        return ('rdx', n, m, l)                      # mov.x @(r0,Rm),Rn
    if t == 0 and l in (4, 5, 6):
        return ('wrx', n, m, l)                      # mov.x Rm,@(r0,Rn)
    if t == 3 and l == 0xC:
        return ('add', n, m, 0)
    if t == 7:
        return ('addi', n, 0, w & 0xFF)
    if (t == 2 and l in (0xE, 0xF)) or (t == 0 and l == 7):
        return ('mul', n, m, 0)
    if t == 4 and (w & 0xFF) in (0x00, 0x04, 0x08, 0x18, 0x28, 0x01, 0x05, 0x09, 0x19, 0x29, 0x24, 0x25):
        return ('shift', n, 0, 0)
    if t == 4 and (w & 0xFF) == 0x0B:
        return ('jsr', n, 0, 0)
    if t == 4 and (w & 0xFF) == 0x2B:
        return ('jmp', n, 0, 0)
    if t == 0xB:
        return ('bsr', 0, 0, 0)
    if t == 0xA:
        return ('bra', 0, 0, 0)
    if w == 0x000B:
        return ('rts', 0, 0, 0)
    if t == 3 and l in (8, 0xA, 0xE):
        return ('alu', n, m, l)                      # sub / subc / addc: writes Rn
    if t == 2 and l in (8, 9, 0xA, 0xB):
        return ('alu2', n, m, l)                     # tst / and / xor / or
    if t == 0xE:
        return ('movi', n, 0, w & 0xFF)
    return ('other', n, m, l)


def _rd(d, o):
    return struct.unpack_from('<H', d, o)[0]


def uses(d, pc, reg):
    """use tags of the pointer loaded into `reg` by the load at pc (see the module doc)"""
    tags = set()
    A = {reg}
    k = 1
    ended = False
    while k <= 36 and not ended:
        o = pc + 2 * k
        if o + 2 > len(d):
            break
        kind, n, m, x = decode(_rd(d, o))
        k += 1
        if kind in ('rts', 'bra', 'jmp'):
            ended = True                             # the delay slot still counts
            if o + 4 > len(d):
                break
            kind, n, m, x = decode(_rd(d, o + 2))
        if kind == 'mov':
            if m in A:
                A.add(n)
            elif n in A:
                A.discard(n)
        elif kind == 'add':
            if n in A or m in A:
                tags.add('add')
        elif kind == 'addi':
            if n in A:
                tags.add('add')
        elif kind == 'mul':
            if n in A or m in A:
                tags.add('mul')
        elif kind == 'shift':
            if n in A:
                tags.add('shift')
        elif kind in ('rdx', 'wrx'):
            if m in A or (kind == 'wrx' and n in A):
                tags.add('idx')
        elif kind in ('rdd', 'rdd0'):
            if m in A:
                tags.add('disp')
            if kind == 'rdd' and n in A:
                A.discard(n)
        elif kind == 'wrd':
            if n in A:
                tags.add('disp' if x else 'disp0')
            if m in A:
                tags.add('stored')
        elif kind == 'wrd0':
            if n in A or m in A:
                tags.add('disp')
        elif kind == 'rd':
            if m in A:
                tags.add('read')
            if n in A and x not in (4, 5, 6):
                A.discard(n)
        elif kind == 'wr':
            if m in A:
                tags.add('stored')
            if n in A:
                tags.add('read')
        elif kind in ('jsr', 'bsr'):
            if A & {4, 5, 6, 7}:
                tags.add('call')
            A -= {0, 1, 2, 3, 4, 5, 6, 7}
        elif kind in ('movi', 'ldlit', 'alu', 'alu2'):
            if n in A and (kind != 'alu2' or x != 8):
                A.discard(n)
        if not A:
            break
    for k in range(1, 7):                            # a multiply by the stride hoisted in front of the load
        o = pc - 2 * k
        if o < 0:
            break
        if decode(_rd(d, o))[0] == 'mul':
            tags.add('mulb')
    return tags


def classify_tags(tags):
    if tags & BASE_TAGS:
        return 'base'
    if tags == {'call'}:
        return 'text'
    return 'unknown'


class ImageIndex:
    """per-image lookups for site analysis: pointer words (offset -> in-image pointer), literal loads, targets"""

    def __init__(self, data, base):
        self.data, self.base = data, base
        n = len(data) // 4
        words = struct.unpack('<%dI' % n, data[:n * 4])
        lo, hi = base, base + len(data)
        self.targets = {}
        self.ptrword = set()
        for i, w in enumerate(words):
            if lo <= w < hi:
                self.targets.setdefault(w - base, []).append(i * 4)
                self.ptrword.add(i * 4)
        self._lits = None

    @property
    def lits(self):
        if self._lits is None:
            self._lits = literal_loads(self.data)
        return self._lits

    def site_report(self, off):
        """[(kind, word offset, use tags text, class)] for every pointer word naming the target at file offset `off`"""
        out = []
        for w in self.targets.get(off, []):
            ld = self.lits.get(w, [])
            tg, tg_out = set(), set()
            for pc, reg, in_code in ld:
                (tg if in_code else tg_out).update(uses(self.data, pc, reg))
            if any(x[2] for x in ld):
                out.append(('lit', w, ','.join(sorted(tg | (tg_out & BASE_TAGS))) or '-', classify_tags(tg | (tg_out & BASE_TAGS))))
            elif tg_out & BASE_TAGS:
                # a load outside the recognised code windows (a function in a sparse state machine) that indexes the pointer: believe it
                out.append(('litx', w, ','.join(sorted(tg_out)), 'base'))
            elif (w - 4) in self.ptrword or (w + 4) in self.ptrword:
                out.append(('ptrtab', w, '-', 'text'))
            else:
                out.append(('field', w, '-', 'unknown'))
        return out


def site_verdict(sites):
    """('text' | 'base' | 'unknown', reason) from a site_report()"""
    if not sites:
        return 'unknown', 'no pointer word found'
    bad = [s for s in sites if s[3] == 'base']
    if bad:
        return 'base', 'literal used with index arithmetic: ' + ';'.join('%x:%s' % (s[1], s[2]) for s in bad)
    bad = [s for s in sites if s[3] != 'text']
    if bad:
        return 'unknown', ';'.join('%s@%x:%s' % (s[0], s[1], s[2]) for s in bad)
    return 'text', ''


def _hexoff(rid):
    return int(rid.rsplit('#', 1)[1], 16)


def array_heads(recs, others=()):
    """Offsets of hwptr records that are element 0 of a fixed-stride array: the pointers to such a record address the ARRAY (code
    indexes base + n*S), so the string must never be moved (and its slot is not an arena).  Rule A: a `recarr` record
    (ctx `recarray S=<n> ...`) sits exactly one stride behind.  Rule B: the record is a single-pointer record (`hwptr ptr@..`) and
    `hwpool` records sit at +S and +2S (sponsor / company arrays of stride 76 / 184).  s8ft, 2026-11-12: SCDRF 0x37df0 `Damui`
    (11 pointers, stride 56) was moved by --refit on (hw-relocate), so the scout screen read the string pool as 56 byte records."""
    byoff = {}
    for r in list(recs) + list(others):
        byoff[_hexoff(r['id'])] = r
    heads = set()
    for r in recs:
        if r.get('fmt') != 'hwptr' or (r.get('refs') or 0) <= 0:
            continue
        off = _hexoff(r['id'])
        if 'hwptr tbl@' in (r.get('ctx') or ''):
            continue                 # an entry of a table of string pointers (the +S neighbour is a coincidence of the extraction: s8gkc, BACKUP club
                                     # words 'Panthera' / 'Mythos' at 0x3c968 / 0x3c9e0 next to a spurious recarray); a head is addressed by a lone literal
        single = 'hwptr ptr@' in (r.get('ctx') or '')
        for S in range(4, 257):
            o1 = byoff.get(off + S)
            if not o1:
                continue
            m = re.search(r'recarray S=(\d+)', o1.get('ctx') or '')
            if o1.get('fmt') == 'recarr' and m and int(m.group(1)) == S:
                heads.add(off)
                break
            o2 = byoff.get(off + 2 * S)
            if single and 'hwpool' in (o1.get('ctx') or '') and o2 and 'hwpool' in (o2.get('ctx') or ''):
                heads.add(off)
                break
    return heads
